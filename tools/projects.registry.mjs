/**
 * The portfolio project registry: one source of truth for every project the
 * site represents.
 *
 * `tools/generate-project-metadata.mjs` iterates this list and writes
 * `data/projects.generated.json`; the frontend reads only that JSON, so adding
 * a project here plus dropping the notification workflow into its repository is
 * the whole onboarding path (docs/project-metadata.md).
 *
 * `id` must match a `ProjectId` in `src/types.d.ts` and a key in
 * `PORTFOLIO.projects` (src/data.ts), because the curated prose timeline and
 * the generated metadata are merged on that id.
 */

/**
 * @typedef {object} VersionSource
 * @property {'file'|'release'} from
 *   `release` reads the newest published GitHub Release tag. `file` reads a
 *   tracked file on the default branch and joins the first capture group of
 *   each pattern.
 * @property {string} [path] Repository-relative path, required when from ==='file'.
 * @property {string[]} [patterns] Regex sources, each with one capture group.
 * @property {string} [join] Separator for the captures. Defaults to '.'.
 */

/**
 * @typedef {object} MilestoneSource
 * @property {'releases'|'tags'|'verEntries'} from
 * @property {string} [path] Directory of `.ver` files, required for verEntries.
 */

/**
 * @typedef {object} ProjectRegistryEntry
 * @property {string} id
 * @property {string} label
 * @property {string|null} repo `owner/name`, or null when no public repository exists.
 * @property {string|null} liveUrl Published, browsable URL, or null.
 * @property {boolean} metadataEnabled Whether the generator queries GitHub for this project.
 * @property {boolean} [countCommits] Fetch the default-branch commit total. Default true.
 * @property {boolean} [countMergedPullRequests] Fetch the merged-PR total. Default true.
 * @property {VersionSource|null} [version] How to resolve a displayed version. Default null.
 * @property {MilestoneSource[]} [milestones] Deterministic milestone signals, in priority order.
 * @property {string} [note] Why a project is not automated, for the generated JSON and docs.
 */

