/** Registry entries the generator will actually query. */
export const trackedProjects = () => PROJECTS.filter(
  (project) => project.metadataEnabled && typeof project.repo === 'string',
);

/**
 * Look a project up by the `owner/name` a repository_dispatch payload carries.
 * Matching is case-insensitive because GitHub treats repository names that way.
 */
export const projectForRepository = (repository) => {
  const needle = String(repository ?? '').toLowerCase();
  return PROJECTS.find((project) => project.repo?.toLowerCase() === needle);
};
